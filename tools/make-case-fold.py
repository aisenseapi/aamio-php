# Writes src/CaseFold.php: the lower case of every character outside ASCII whose lower case differs, as Python's
# str.lower() gives it, and the two sets Unicode's rule for a final sigma looks at. aamio-python and the Node runtime
# compare names apart from upper and lower case in all of Unicode, and mb_strtolower, which would do the same in PHP,
# needs mbstring, which a PHP does not always have.
#
#     python tools/make-case-fold.py
#
# Run it with the Python whose Unicode the table is to follow, and run the tests after.
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "src", "CaseFold.php")
SIGMA = "\u03a3"
FINAL = "\u03c2"


def php(text):
    """A PHP double-quoted string of these characters: ASCII as it is, everything else as \\u{...}."""
    out = []
    for char in text:
        code = ord(char)
        if 0x20 <= code < 0x7F and char not in '"\\$':
            out.append(char)
        else:
            out.append("\\u{%X}" % code)
    return '"' + "".join(out) + '"'


def spans(codes):
    """Code points in order, as runs of [first, last]."""
    out = []
    for code in codes:
        if out and out[-1][1] == code - 1:
            out[-1][1] = code
        else:
            out.append([code, code])
    return "\n".join("        [0x%X, 0x%X]," % (first, last) for first, last in out)


lowered = []
ignorable = []
cased = []
for code in range(0x110000):
    if 0xD800 <= code <= 0xDFFF:
        continue
    char = chr(code)
    # A capital sigma is final when a cased character comes before it and none
    # after it, case-ignorable ones passed over on both sides. Python does not
    # give the two sets by name, so they are read off what lower() does with a
    # character before the sigma alone, and between a cased letter and it.
    alone = (char + SIGMA).lower()[-1] == FINAL
    between = ("A" + char + SIGMA).lower()[-1] == FINAL
    if between and not alone:
        ignorable.append(code)
    elif alone:
        cased.append(code)
    if code >= 0x80 and char != SIGMA and char.lower() != char:
        lowered.append("        %s => %s," % (php(char), php(char.lower())))

source = '''<?php

declare(strict_types=1);

namespace Aamio;

/**
 * Lower case for comparing names apart from upper and lower case, as
 * aamio-python's str.lower() and the Node runtime's toLowerCase() give it,
 * without mbstring, which a PHP does not always have. strtolower lowers ASCII
 * alone, so two names that differed only in the case of a letter outside ASCII
 * were two names here and one in the other two runtimes (a check of 12
 * November 2026).
 *
 * Generated by tools/make-case-fold.py from Python %(python)s.
 * Do not edit: run the script again.
 */
final class CaseFold
{
    /** The Unicode version the tables follow. */
    public const UNICODE = '%(unicode)s';

    /** @var array<string, string> every character outside ASCII whose lower case differs, capital sigma apart */
    private const MAP = [
%(lowered)s
    ];

    /** @var list<array{int, int}> what the rule for a final sigma passes over (Case_Ignorable) */
    private const IGNORABLE = [
%(ignorable)s
    ];

    /** @var list<array{int, int}> what the rule for a final sigma counts as cased, apart from what it passes over */
    private const CASED = [
%(cased)s
    ];

    /** The lower case of a text, character by character, with a capital sigma that ends a word as a final sigma. */
    public static function lower(string $text): string
    {
        if (preg_match('/[^\\x00-\\x7F]/', $text) !== 1) {
            return strtolower($text);
        }
        $chars = preg_split('//u', $text, -1, PREG_SPLIT_NO_EMPTY);
        if ($chars === false) {
            // Not UTF-8: lowered as bytes, as before.
            return strtolower($text);
        }
        $out = '';
        foreach ($chars as $at => $char) {
            if ($char === "\\u{3A3}") {
                $out .= self::finalSigma($chars, $at) ? "\\u{3C2}" : "\\u{3C3}";
            } elseif (strlen($char) === 1) {
                $out .= strtolower($char);
            } else {
                $out .= self::MAP[$char] ?? $char;
            }
        }

        return $out;
    }

    /**
     * Whether a capital sigma ends a word, as Unicode's Final_Sigma has it and
     * str.lower() does it: a cased character before it and none after it, with
     * case-ignorable ones passed over on both sides.
     *
     * @param list<string> $chars
     */
    private static function finalSigma(array $chars, int $at): bool
    {
        $before = null;
        for ($i = $at - 1; $i >= 0; $i--) {
            $code = self::codePoint($chars[$i]);
            if (!self::within(self::IGNORABLE, $code)) {
                $before = $code;
                break;
            }
        }
        if ($before === null || !self::within(self::CASED, $before)) {
            return false;
        }
        for ($i = $at + 1, $n = count($chars); $i < $n; $i++) {
            $code = self::codePoint($chars[$i]);
            if (!self::within(self::IGNORABLE, $code)) {
                return !self::within(self::CASED, $code);
            }
        }

        return true;
    }

    /** The code point of one character, which preg_split has found to be UTF-8. */
    private static function codePoint(string $char): int
    {
        $first = ord($char[0]);

        return match (strlen($char)) {
            1 => $first,
            2 => (($first & 0x1F) << 6) | (ord($char[1]) & 0x3F),
            3 => (($first & 0x0F) << 12) | ((ord($char[1]) & 0x3F) << 6) | (ord($char[2]) & 0x3F),
            default => (($first & 0x07) << 18) | ((ord($char[1]) & 0x3F) << 12) | ((ord($char[2]) & 0x3F) << 6) | (ord($char[3]) & 0x3F),
        };
    }

    /**
     * Whether a code point is in one of the runs, which are in order.
     *
     * @param list<array{int, int}> $runs
     */
    private static function within(array $runs, int $code): bool
    {
        $low = 0;
        $high = count($runs) - 1;
        while ($low <= $high) {
            $middle = intdiv($low + $high, 2);
            if ($code < $runs[$middle][0]) {
                $high = $middle - 1;
            } elseif ($code > $runs[$middle][1]) {
                $low = $middle + 1;
            } else {
                return true;
            }
        }

        return false;
    }
}
''' % {
    "python": sys.version.split()[0],
    "unicode": unicodedata.unidata_version,
    "lowered": "\n".join(lowered),
    "ignorable": spans(ignorable),
    "cased": spans(cased),
}

with open(TARGET, "w", encoding="utf-8", newline="\n") as handle:
    handle.write(source)
print("written %s: %d lower cases, %d case-ignorable and %d cased code points, Unicode %s"
      % (os.path.normpath(TARGET), len(lowered), len(ignorable), len(cased), unicodedata.unidata_version))
